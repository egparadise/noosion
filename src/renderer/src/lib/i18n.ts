export type I18nKey = keyof typeof dict

export function t(key: I18nKey): string {
  return dict[key][ui.get().settings.locale] ?? dict[key].en
}

/** Hook form: subscribes to locale changes so the component re-renders on switch. */
export function useT(): (key: I18nKey) => string {
  const locale = ui.use((s) => s.settings.locale)
  return (key) => dict[key][locale] ?? dict[key].en
}

export function relativeTime(ts: number): string {
  const diff = Math.max(0, Date.now() - ts)
  const m = Math.floor(diff / 60000)
  if (m < 1) return t('justNow')
  if (m < 60) return `${m}${t('minutesAgo')}`
  const h = Math.floor(m / 60)
  if (h < 24) return `${h}${t('hoursAgo')}`
  return `${Math.floor(h / 24)}${t('daysAgo')}`
}
